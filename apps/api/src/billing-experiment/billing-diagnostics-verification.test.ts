import { describe, expect, test } from "bun:test";
import { VerificationStatus } from "@crm/db";
import type { MetabaseResult } from "../metabase/metabase.client";
import { billingDiagnosticsVerificationChecks } from "./billing-diagnostics-verification";

const names = [
	"section",
	"arm",
	"tier",
	"assigned",
	"paid_converters",
	"topup_users",
	"topup_revenue_usd",
	"repeat_topup_orgs",
	"canceled",
	"pending_cancel",
	"renewal_eligible",
	"renewed",
	"failed_invoice_count",
	"failed_invoice_amount_usd",
	"cancellation_reason",
	"cancellation_reason_count",
	"data_through",
];

function result(rows: unknown[][]): MetabaseResult {
	return {
		columns: names.map((name) => ({ name, displayName: name, baseType: null })),
		rows,
	};
}

describe("billing diagnostics verification", () => {
	test("passes a reconciled two-arm diagnostic pack", () => {
		const checks = billingDiagnosticsVerificationChecks(
			result([
				[
					"summary",
					"v2 control",
					null,
					10,
					4,
					0,
					0,
					0,
					1,
					0,
					3,
					2,
					1,
					29,
					null,
					null,
					"2026-08-26",
				],
				[
					"tier",
					"v2 control",
					"creator",
					10,
					4,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					"2026-08-26",
				],
				[
					"reason",
					"v2 control",
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					"too_expensive",
					1,
					"2026-08-26",
				],
				[
					"summary",
					"v3 treatment",
					null,
					12,
					6,
					2,
					50,
					1,
					0,
					1,
					4,
					3,
					0,
					0,
					null,
					null,
					"2026-08-26",
				],
				[
					"tier",
					"v3 treatment",
					"pro",
					12,
					6,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					"2026-08-26",
				],
			]),
		);

		expect(checks.map((check) => check.status)).toEqual(
			Array(8).fill(VerificationStatus.PASSED),
		);
	});

	test("fails when tiers or renewal counts do not reconcile", () => {
		const checks = billingDiagnosticsVerificationChecks(
			result([
				[
					"summary",
					"v2 control",
					null,
					10,
					4,
					0,
					0,
					0,
					0,
					0,
					2,
					3,
					0,
					0,
					null,
					null,
					"2026-08-26",
				],
				[
					"tier",
					"v2 control",
					"creator",
					5,
					2,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					"2026-08-26",
				],
				[
					"summary",
					"v3 treatment",
					null,
					12,
					6,
					2,
					50,
					1,
					0,
					0,
					4,
					3,
					0,
					0,
					null,
					null,
					"2026-08-26",
				],
				[
					"tier",
					"v3 treatment",
					"pro",
					12,
					6,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					null,
					"2026-08-26",
				],
			]),
		);

		expect(checks.find((check) => check.name === "tier_mapping")?.status).toBe(
			VerificationStatus.FAILED,
		);
		expect(
			checks.find((check) => check.name === "renewal_maturity")?.status,
		).toBe(VerificationStatus.FAILED);
	});
});
